    [Fact]
    public void The_chunked_fixture_generator_reproduces_the_committed_bytes()
    {
        var complete = PhoneBundleFixture.Generate(chunked: true);
        var incomplete = PhoneBundleFixture.Generate(chunked: true, incomplete: true);
        var readme = Path.ChangeExtension(PhoneBundleFixture.ChunkedPath(false), ".README.md");
        var notes = PhoneBundleFixture.ChunkedReadme(complete, incomplete);
        var regenerate = Environment.GetEnvironmentVariable("DICTUM_REGENERATE_PHONE_FIXTURE") == "1";
        if (regenerate) File.WriteAllText(readme, notes, new UTF8Encoding(false));
        foreach (var cutShort in new[] { false, true })
        {
            var generated = cutShort ? incomplete : complete;
            var path = PhoneBundleFixture.ChunkedPath(cutShort);
            if (regenerate) File.WriteAllBytes(path, generated);
            using var committedZip = ZipFile.OpenRead(path);
            using var generatedZip = new ZipArchive(new MemoryStream(generated), ZipArchiveMode.Read);
            Assert.Equal(new[] { "audio-mixed.chunks.enc", "confirmations.json.enc", "meta.json.enc", "manifest.json" },
                committedZip.Entries.Select(e => e.FullName));
            Assert.Equal(committedZip.Entries.Select(e => e.FullName), generatedZip.Entries.Select(e => e.FullName));
            foreach (var entry in committedZip.Entries)
            {
                Assert.Equal(entry.Length, entry.CompressedLength);
                Assert.Equal(entry.Length, generatedZip.GetEntry(entry.FullName)!.CompressedLength);
                Assert.Equal(Entry(committedZip, entry.FullName), Entry(generatedZip, entry.FullName));
            }
            // Whole-file comparison also pins stored methods, headers, timestamps, order and central directory.
            Assert.Equal(File.ReadAllBytes(path), generated);
            var audio = Entry(committedZip, "audio-mixed.chunks.enc");
            Assert.Equal(cutShort ? 64144 : 64204, audio.Length);
            Assert.Equal(32000, BinaryPrimitives.ReadInt32LittleEndian(audio.AsSpan(24)));
            Assert.Equal(32000, BinaryPrimitives.ReadInt32LittleEndian(audio.AsSpan(32084)));
            if (!cutShort) Assert.Equal(0, BinaryPrimitives.ReadInt32LittleEndian(audio.AsSpan(64144)));
        }
        Assert.Equal(notes, File.ReadAllText(readme));
        Assert.DoesNotContain('\r', File.ReadAllText(readme));
    }

    [Theory]
    [InlineData(false, false)]
    [InlineData(true, false)]
    [InlineData(false, true)]
    [InlineData(true, true)]
    public async Task The_committed_chunked_fixtures_import_and_transcribe_as_Mixed(bool incomplete, bool regenerate)
    {
        using var target = new MeetingFixture();
        var path = PhoneBundleFixture.ChunkedPath(incomplete);
        // Also exercise freshly generated bytes, so a writer change must remain readable independently of golden files.
        if (regenerate)
        {
            Directory.CreateDirectory(target.Root);
            path = Path.Combine(target.Root, "generated.dictum");
            File.WriteAllBytes(path, PhoneBundleFixture.Generate(chunked: true, incomplete: incomplete));
        }
        var transcriber = new FakeTranscriber(target.Store());
        Assert.Equal(PhoneBundleFixture.Id, await Importer(target, transcriber: transcriber)
            .ImportAsync(path, PhoneBundleFixture.Code, "Synthetic importer", ct: TestContext.Current.CancellationToken));
        var meta = Assert.Single(target.Store().List());
        Assert.Equal(MeetingSource.Phone, meta.Source);
        Assert.Equal(PhoneBundleFixture.PROPOSED_Title, meta.Title);
        Assert.Equal(PhoneBundleFixture.At, meta.StartedAt);
        Assert.Equal(TimeSpan.FromSeconds(2), meta.Duration);
        Assert.Equal(incomplete ? new[] { Channel.Mixed } : [], meta.IncompleteAudioChannels);
        Assert.Equal(incomplete, meta.AudioIncomplete);
        using var audio = target.Store().OpenAudio(meta.Id, Channel.Mixed);
        using var copy = new MemoryStream(); audio.CopyTo(copy);
        Assert.Equal(44 + 64000, copy.Length);
        Assert.Equal(PhoneBundleFixture.Wav(), copy.ToArray());
        Assert.True(transcriber.Parts > 0);
        var segments = target.Store().ReadTranscript(meta.Id);
        Assert.NotEmpty(segments);
        Assert.All(segments, segment => Assert.Equal(Channel.Mixed, segment.Channel));
    }

    [Fact]
    public void A_framing_tag_sealed_with_length_zero_in_its_AAD_is_refused()
    {
        using var files = new MeetingFixture();
        Directory.CreateDirectory(files.Root);
        var path = Path.Combine(files.Root, "audio-mixed.chunks.enc");
        var header = "DCTMAUD\u0001"u8.ToArray().Concat(PhoneBundleFixture.Range(0, 16)).ToArray();
        var identity = Encoding.UTF8.GetBytes(PhoneBundleFixture.Id.Value + "/audio-mixed.chunks.enc");
        using var aes = new AesGcm(PhoneBundleFixture.Range(0, 32), 16);
        foreach (var wrongLength in new[] { false, true })
        {
            using (var stream = File.Create(path))
            {
                stream.Write(header);
                Record(0, PhoneBundleFixture.Wav()[44..32044]);
                Record(1, []); // valid terminal: refusal cannot be attributed to a missing terminal

                void Record(int sequence, byte[] pcm)
                {
                    var aad = header.Concat(new byte[12]).Concat(identity).ToArray();
                    BinaryPrimitives.WriteInt64LittleEndian(aad.AsSpan(24), sequence);
                    BinaryPrimitives.WriteInt32LittleEndian(aad.AsSpan(32), pcm.Length);
                    var payloadNonce = PhoneBundleFixture.Range(0x10 + sequence * 0x20, 12);
                    var frameNonce = PhoneBundleFixture.Range(0x20 + sequence * 0x20, 12);
                    var cipher = new byte[pcm.Length]; var payloadTag = new byte[16]; var frameTag = new byte[16];
                    aes.Encrypt(payloadNonce, pcm, cipher, payloadTag, aad);
                    stream.Write(aad.AsSpan(32, 4));
                    if (wrongLength) BinaryPrimitives.WriteInt32LittleEndian(aad.AsSpan(32), 0);
                    aes.Encrypt(frameNonce, ReadOnlySpan<byte>.Empty, Span<byte>.Empty, frameTag, aad);
                    stream.Write(frameNonce); stream.Write(frameTag);
                    stream.Write(payloadNonce); stream.Write(cipher); stream.Write(payloadTag);
                }
            }
            foreach (var incomplete in new[] { false, true })
            {
                using var reader = MeetingCrypto.OpenChunkedAudio(path, PhoneBundleFixture.Range(0, 32),
                    Encoding.UTF8.GetString(identity), incomplete);
                if (wrongLength)
                {
                    var destination = Enumerable.Repeat((byte)0xcc, 100).ToArray();
                    Assert.Throws<CryptographicException>(() => reader.Read(destination));
                    Assert.All(destination, b => Assert.Equal(0xcc, b)); // even the WAV header was withheld
                }
                else
                {
                    using var copy = new MemoryStream(); reader.CopyTo(copy);
                    Assert.Equal(44 + 32000, copy.Length);
                    Assert.Equal(PhoneBundleFixture.Wav()[44..32044], copy.ToArray()[44..]);
                }
            }
        }
    }

    [Fact]
    public async Task A_bundle_with_an_unknown_agreement_method_shows_the_damaged_message()
    {
        using var target = new MeetingFixture();
        Directory.CreateDirectory(target.Root);
        var path = Path.Combine(target.Root, "unknown-how.dictum");
        File.Copy(PhoneBundleFixture.PathInWorktree, path);
        var meta = JsonNode.Parse(JsonSerializer.SerializeToUtf8Bytes(PhoneBundleFixture.Meta))!;
        meta["Agreement"]!["How"] = "unknown";
        using var plain = new MemoryStream(JsonSerializer.SerializeToUtf8Bytes(meta));
        using var encrypted = new MemoryStream();
        MeetingCrypto.Encrypt(plain, encrypted, PhoneBundleFixture.Range(0, 32), PhoneBundleFixture.Id.Value + "/meta.json.enc");
        ChangeEntry(path, "meta.json.enc", _ => encrypted.ToArray());
        ChangeManifest(path, manifest => manifest["files"]!.AsArray().Single(f => (string?)f!["name"] == "meta.json.enc")!["bytes"] = encrypted.Length);
        var prompted = false;
        var importer = Importer(target, (_, _, _) => { prompted = true; return Task.FromResult<Agreement?>(null); });
        var error = await Assert.ThrowsAsync<InvalidDataException>(() => importer.ImportAsync(path, PhoneBundleFixture.Code,
            "Synthetic importer", ct: TestContext.Current.CancellationToken));
        Assert.Equal(BundleText.PROPOSED_Invalid, error.Message);
        Assert.False(prompted);
        Assert.Empty(target.Store().List());
        Assert.Empty(Directory.GetDirectories(target.Root));
    }
