namespace Dictum.Meetings.Summaries;

public static class SummaryCaption
{
    // PROPOSED: owner to approve
    public const string Local_PROPOSED = "Summary generated locally by a small model. Check it against the transcript before relying on it.";
    // PROPOSED: owner to approve
    public const string Ollama_PROPOSED = "Summary generated on this computer by the model you chose in Ollama. Check it against the transcript.";
    // PROPOSED: owner to approve
    public const string OwnKey_PROPOSED = "Summary generated by {provider} with your own key. Your transcript text left this computer. Check it against the transcript.";

    public static string For(string engine) => For(engine, null);

    public static string For(string engine, string? provider) => engine switch
    {
        "Local" => Local_PROPOSED,
        "Ollama" => Ollama_PROPOSED,
        "OwnKey" => OwnKey_PROPOSED.Replace("{provider}",
            string.IsNullOrWhiteSpace(provider) ? throw new ArgumentException("An own-key provider name is required.", nameof(provider)) : provider,
            StringComparison.Ordinal),
        _ => throw new ArgumentException("Unknown summary engine.", nameof(engine))
    };
}
