// Unicode script ranges for letters, generated from Node 24's Unicode 17.0
// Script properties. Common and Inherited letters have no script of their own.
// Non-letter gaps may be included; callers classify letters only.
internal static class UnicodeLetterScripts
{
    public static int Get(int value)
    {
        var low = 0;
        var high = Ranges.Length - 1;
        while (low <= high)
        {
            var middle = low + (high - low) / 2;
            var range = Ranges[middle];
            if (value < range.Start) high = middle - 1;
            else if (value > range.End) low = middle + 1;
            else return range.Script;
        }
        // Fail closed for letters introduced after this Unicode version.
        return -1;
    }

